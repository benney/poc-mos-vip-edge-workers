// Bundles the playground for one example.
//   node scripts/build-web.mjs [example]
//
// lol-html's CommonJS entry pulls in fs/path/util/assert and reads its .wasm
// synchronously at import, so those are aliased to shims and the wasm is inlined.
import { build } from 'esbuild';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { ROOT, findWorker, presetsFor, workerFrom } from './paths.mjs';

const found = findWorker(workerFrom(process.argv));
const { name } = found;
const p = (...parts) => resolve(ROOT, ...parts);

const wasm = p('build', name, 'release.wasm');
if (!existsSync(wasm)) {
    console.error(`missing ${wasm} — run \`node scripts/build.mjs ${name}\` first.`);
    process.exit(1);
}
const presets = presetsFor(found);
if (!existsSync(presets)) {
    console.error(`${presets} is required for the playground.`);
    process.exit(1);
}

mkdirSync(p('playground/dist'), { recursive: true });

// Inline lol-html's wasm for the fs shim.
const lolWasm = readFileSync(p('node_modules/html-rewriter-wasm/dist/html_rewriter_bg.wasm'));
writeFileSync(
    p('devkit/shims/lolhtml-wasm.cjs'),
    `// Generated by scripts/build-web.mjs — lol-html wasm inlined for the browser.\nmodule.exports = "${lolWasm.toString('base64')}";\n`,
);

// html-rewriter-wasm writes `require(String.raw`./asyncify.js`)` to defeat bundlers.
// Normalise those to static requires so esbuild can resolve them.
const staticRequires = {
    name: 'static-requires',
    setup(b) {
        b.onLoad({ filter: /html-rewriter-wasm[\\/]dist[\\/].*\.js$/ }, (args) => ({
            contents: readFileSync(args.path, 'utf8').replace(
                /require\(String\.raw`([^`]+)`\)/g,
                (_, target) => `require(${JSON.stringify(target)})`,
            ),
            loader: 'js',
        }));
    },
};

const common = {
    bundle: true, format: 'iife', target: 'es2022', logLevel: 'warning',
    plugins: [staticRequires],
    alias: {
        '#presets': presets,
        fs: p('devkit/shims/fs.cjs'),
        path: p('devkit/shims/path.cjs'),
        util: p('devkit/shims/util.cjs'),
        assert: p('devkit/shims/assert.cjs'),
    },
    // html_rewriter.js builds a filesystem path for its .wasm; the fs shim ignores it,
    // but the identifiers still have to resolve in a bundle.
    define: { __dirname: '"/"', __filename: '"/html_rewriter.js"' },
};

await build({ ...common, entryPoints: [p('playground/worker.mjs')], outfile: p('playground/dist/worker.js') });
await build({ ...common, entryPoints: [p('playground/ui.mjs')], outfile: p('playground/dist/ui.js') });

copyFileSync(wasm, p('playground/dist/release.wasm'));
copyFileSync(p('playground/index.html'), p('playground/dist/index.html'));

const kb = (f) => `${(readFileSync(f).length / 1024).toFixed(0)} KB`;
console.log(`built playground/dist for "${name}":
  worker.js     ${kb(p('playground/dist/worker.js'))}  (host + lol-html, wasm inlined)
  ui.js         ${kb(p('playground/dist/ui.js'))}
  release.wasm  ${kb(p('playground/dist/release.wasm'))}`);
